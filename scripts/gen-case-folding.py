#!/usr/bin/env python3
"""Writes crates/marknotes-sync/src/case_folding.rs from Unicode's CaseFolding.txt.

The sync path key is Unicode simple case folding: the C and S mappings, one character to one. The table is generated
from a pinned version of the data file, checked against its SHA-256, so the output is the same on every machine.

Usage: scripts/gen-case-folding.py [CaseFolding.txt]   (downloads the pinned file when no path is given)
"""

import hashlib
import pathlib
import sys
import urllib.request

VERSION = "17.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/CaseFolding.txt"
SHA256 = "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183"
OUT = pathlib.Path(__file__).resolve().parent.parent / "crates" / "marknotes-sync" / "src" / "case_folding.rs"


def main() -> None:
    data = pathlib.Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"CaseFolding.txt has SHA-256 {digest}, expected {SHA256} (Unicode {VERSION})")

    pairs = []
    for line in data.decode("utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping = (field.strip() for field in line.split(";")[:3])
        if status in ("C", "S"):
            pairs.append((int(code, 16), int(mapping, 16)))
    pairs.sort()

    lines = [
        f"// Generated by scripts/gen-case-folding.py from Unicode {VERSION} CaseFolding.txt; do not edit.",
        "",
        "/// The `C` and `S` mappings of CaseFolding.txt, sorted by the character folded.",
        "#[rustfmt::skip]",
        f"pub(crate) const SIMPLE_CASE_FOLDING: [(char, char); {len(pairs)}] = [",
    ]
    lines += [f"    ('\\u{{{a:04X}}}', '\\u{{{b:04X}}}')," for a, b in pairs]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {len(pairs)} mappings to {OUT}")


if __name__ == "__main__":
    main()
